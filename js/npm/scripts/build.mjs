import { copyFileSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '..', '..');

const defaultSource = join(repoRoot, 'dist', 'affidavit_wasm.wasm');
const source = process.env.AFFIDAVIT_WASM_SOURCE ?? defaultSource;
const bytes = readFileSync(source);
const sha = createHash('sha256').update(bytes).digest('hex');

mkdirSync(join(pkgRoot, 'wasm'), { recursive: true });
copyFileSync(source, join(pkgRoot, 'wasm', 'affidavit.wasm'));

const meta = `// GENERATED by scripts/build.mjs from dist/affidavit_wasm.wasm.
export const WASM_SHA256 = '${sha}';
`;
mkdirSync(join(pkgRoot, 'src', 'generated'), { recursive: true });
writeFileSync(join(pkgRoot, 'src', 'generated', 'artifact-meta.ts'), meta);
console.log(`build: wasm/affidavit.wasm in place (sha256 ${sha})`);
