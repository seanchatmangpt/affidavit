#!/usr/bin/env python3
"""Render one markdown page per VerbEntry from src/registry.rs.

Register row 20 fix path: README/CLAUDE.md verb tables drift from REGISTRY
(the 83/79/101 count-drift class). This generator makes per-verb doc pages a
projection of the registry, not a hand-maintained table:

    python3 scripts/render_verb_docs.py

The court tests/docs_verb_parity.rs fails loudly on drift and prints this
regen command. Output is deterministic: sorted, no timestamps, same registry
-> byte-identical pages (idempotent regen is the fix path).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = REPO_ROOT / "src" / "registry.rs"
OUT_DIR = REPO_ROOT / "docs" / "reference" / "verbs"

# One VerbEntry::new("verb", "noun", VerbGroup::Group, "summary",
# &[kw, ...]) call, spread over multiple lines. Same approach as
# generate_completions.py; that script's ENTRY_RE stops at the summary,
# this one additionally captures the keywords slice.
ENTRY_RE = re.compile(
    r'VerbEntry::new\(\s*'
    r'"((?:[^"\\]|\\.)*)"\s*,\s*'      # verb
    r'"((?:[^"\\]|\\.)*)"\s*,\s*'      # noun
    r'VerbGroup::(\w+)\s*,\s*'         # group
    r'"((?:[^"\\]|\\.)*)"\s*,\s*'      # summary
    r'&\[(.*?)\]',                     # keywords slice body
    re.DOTALL,
)

_KEYWORD_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')
_ESCAPES = {"\\": "\\", '"': '"', "n": "\n", "t": "\t", "r": "\r"}


def rust_unescape(literal: str) -> str:
    """Decode the escape sequences Rust string literals support (subset)."""
    out: list[str] = []
    i = 0
    while i < len(literal):
        ch = literal[i]
        if ch == "\\" and i + 1 < len(literal):
            nxt = literal[i + 1]
            if nxt in _ESCAPES:
                out.append(_ESCAPES[nxt])
                i += 2
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def parse_registry() -> list[dict]:
    """One row per REGISTRY entry: verb, noun, group, summary, keywords."""
    src = REGISTRY_PATH.read_text(encoding="utf-8")
    rows = []
    for verb, noun, group, summary, kw_body in ENTRY_RE.findall(src):
        keywords = [
            rust_unescape(k) for k in _KEYWORD_RE.findall(kw_body)
        ]
        rows.append(
            {
                "verb": rust_unescape(verb),
                "noun": rust_unescape(noun),
                "group": group,
                "summary": rust_unescape(summary),
                "keywords": keywords,
            }
        )
    if not rows:
        sys.exit(
            "REFUSED_NO_REGISTRY_ENTRIES: parsed 0 VerbEntry rows from "
            f"{REGISTRY_PATH} - the registry text format changed; fix ENTRY_RE."
        )
    return rows


def render_page(row: dict, total: int) -> str:
    """One markdown page per verb, deterministic and sorted."""
    kws = ", ".join(f"`{k}`" for k in row["keywords"])
    return (
        f"<!-- DO-NOT-EDIT: generated by "
        f"`python3 scripts/render_verb_docs.py` from src/registry.rs. "
        f"Hand edits are overwritten; regenerate instead. -->\n"
        f"<!-- registry verb count at generation time: {total} -->\n"
        f"\n"
        f"# {row['verb']}\n"
        f"\n"
        f"- **Verb:** `{row['verb']}`\n"
        f"- **Noun:** `{row['noun']}`\n"
        f"- **Group:** {row['group']}\n"
        f"- **Summary:** {row['summary']}\n"
        f"- **Keywords:** {kws}\n"
    )


def main() -> None:
    rows = parse_registry()
    rows.sort(key=lambda r: r["verb"])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = len(rows)
    for row in rows:
        # Verb tokens repeat across nouns (standing certify vs errc certify),
        # so pages are namespaced: docs/reference/verbs/<noun>/<verb>.md
        noun_dir = OUT_DIR / row["noun"]
        noun_dir.mkdir(parents=True, exist_ok=True)
        path = noun_dir / f"{row['verb']}.md"
        path.write_text(render_page(row, total), encoding="utf-8")
    # Loud census: stale pages for removed/renamed verbs are drift too.
    expected = {
        (r["noun"], f"{r['verb']}.md") for r in rows
    }
    actual = {
        (f.relative_to(OUT_DIR).parts[0], f.name)
        for f in OUT_DIR.glob("*/*.md")
    }
    for noun, name in sorted(actual - expected):
        stale = OUT_DIR / noun / name
        print(f"STALE page (registry no longer has this verb): {noun}/{name}")
        stale.unlink()
    print(f"rendered {total} verb pages into {OUT_DIR}")


if __name__ == "__main__":
    main()
