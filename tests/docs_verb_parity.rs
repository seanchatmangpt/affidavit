//! Register row 20 court: per-verb doc pages are a projection of REGISTRY.
//!
//! Single source of truth: `src/registry.rs`. The renderer
//! `scripts/render_verb_docs.py` emits one markdown page per `VerbEntry`
//! into `docs/reference/verbs/`. This court fails loudly on drift (missing
//! page, stale summary/keywords, count drift) and prints the regen command:
//!
//! ```text
//! python3 scripts/render_verb_parity_fix.py
//! ```

use std::fs;
use std::path::PathBuf;

const REGISTRY_PATH: &str = "src/registry.rs";
const PAGES_DIR: &str = "docs/reference/verbs";
const REGEN_CMD: &str = "python3 scripts/render_verb_docs.py";

/// Mirror of the renderer's ENTRY_RE (generate_completions.py approach):
/// one `VerbEntry::new("verb", "noun", VerbGroup::Group, "summary", &[..])`
/// call, spread over multiple lines.
fn parse_registry(src: &str) -> Vec<Row> {
    use regex::Regex;
    let entry_re = Regex::new(
        r#"(?s)VerbEntry::new\(\s*"(?P<verb>(?:[^"\\]|\\.)*)"\s*,\s*"(?P<noun>(?:[^"\\]|\\.)*)"\s*,\s*VerbGroup::(?P<group>\w+)\s*,\s*"(?P<summary>(?:[^"\\]|\\.)*)"\s*,\s*&\[(?P<kws>.*?)\]"#,
    )
    .expect("static regex compiles");
    let kw_re = Regex::new(r#""((?:[^"\\]|\\.)*)""#).expect("static regex compiles");
    let mut rows = Vec::new();
    for c in entry_re.captures_iter(src) {
        let kws = kw_re
            .captures_iter(c.name("kws").expect("kws group").as_str())
            .map(|k| unescape(k.get(1).expect("kw str").as_str()))
            .collect();
        rows.push(Row {
            verb: unescape(c.name("verb").expect("verb group").as_str()),
            noun: unescape(c.name("noun").expect("noun group").as_str()),
            group: c.name("group").expect("group group").as_str().to_string(),
            summary: unescape(c.name("summary").expect("summary group").as_str()),
            keywords: kws,
        });
    }
    rows
}

struct Row {
    verb: String,
    noun: String,
    group: String,
    summary: String,
    keywords: Vec<String>,
}

fn unescape(literal: &str) -> String {
    let mut out = String::with_capacity(literal.len());
    let mut chars = literal.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch == '\\' {
            if let Some(&nxt) = chars.peek() {
                match nxt {
                    '\\' => out.push('\\'),
                    '"' => out.push('"'),
                    'n' => out.push('\n'),
                    't' => out.push('\t'),
                    'r' => out.push('\r'),
                    other => out.push(other),
                }
                chars.next();
                continue;
            }
        }
        out.push(ch);
    }
    out
}

fn pages_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(PAGES_DIR)
}

/// Byte-exact mirror of the renderer's render_page().
fn expected_page(row: &Row, total: usize) -> String {
    let kws = row
        .keywords
        .iter()
        .map(|k| format!("`{k}`"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "<!-- DO-NOT-EDIT: generated by `python3 scripts/render_verb_docs.py` \
         from src/registry.rs. Hand edits are overwritten; regenerate instead. -->\n\
         <!-- registry verb count at generation time: {total} -->\n\
         \n\
         # {verb}\n\
         \n\
         - **Verb:** `{verb}`\n\
         - **Noun:** `{noun}`\n\
         - **Group:** {group}\n\
         - **Summary:** {summary}\n\
         - **Keywords:** {kws}\n",
        verb = row.verb,
        noun = row.noun,
        group = row.group,
        summary = row.summary,
        kws = kws,
    )
}

#[test]
fn docs_verb_parity_every_registry_entry_has_exact_page() {
    let src = fs::read_to_string(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(REGISTRY_PATH))
        .expect("read src/registry.rs");
    let mut rows = parse_registry(&src);
    // Match the rendered pages' byte order (PathBuf sort): the page file
    // name is "{verb}.md", so compare on that, not the bare verb token.
    rows.sort_by(|a, b| {
        let ka = format!("{}/{}.md", a.noun, a.verb);
        let kb = format!("{}/{}.md", b.noun, b.verb);
        ka.cmp(&kb)
    });
    assert!(
        !rows.is_empty(),
        "parsed 0 VerbEntry rows from {REGISTRY_PATH} - registry text format \
         changed; fix the regex in tests/docs_verb_parity.rs and the renderer"
    );

    assert_eq!(
        rows.len(),
        affidavit::registry::verb_count(),
        "text-parse census vs compiled verb_count() disagree - parser drift"
    );

    let dir = pages_dir();
    // Pages live at <noun>/<verb>.md — walk the noun subdirectories.
    let mut rendered: Vec<_> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("read_dir {}: {e} — run {REGEN_CMD}", dir.display()))
        .filter_map(|e| e.ok())
        .filter(|e| e.path().is_dir())
        .flat_map(|e| {
            fs::read_dir(e.path())
                .expect("noun dir readable")
                .filter_map(|f| f.ok())
                .map(|f| f.path())
                .collect::<Vec<_>>()
        })
        .filter(|p| p.extension().is_some_and(|x| x == "md"))
        .collect();
    rendered.sort();

    assert_eq!(
        rendered.len(),
        rows.len(),
        "docs/reference/verbs has {} pages but REGISTRY has {} entries — \
         run `{}` to regenerate",
        rendered.len(),
        rows.len(),
        REGEN_CMD
    );

    let total = rows.len();
    let mut expected_names: Vec<String> = rows
        .iter()
        .map(|r| format!("{}/{}.md", r.noun, r.verb))
        .collect();
    expected_names.sort();
    let actual_names: Vec<String> = rendered
        .iter()
        .map(|p| {
            p.strip_prefix(&dir)
                .expect("under pages dir")
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    assert_eq!(
        expected_names, actual_names,
        "page-name set differs from registry verb set — run `{}`",
        REGEN_CMD
    );

    for (row, path) in rows.iter().zip(rendered.iter()) {
        let actual = fs::read_to_string(path)
            .unwrap_or_else(|e| panic!("read {}: {e} — run `{}`", path.display(), REGEN_CMD));
        assert_eq!(
            actual,
            expected_page(row, total),
            "page {} drifted from its registry entry — run `{}`",
            path.display(),
            REGEN_CMD
        );
    }
}

